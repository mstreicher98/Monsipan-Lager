export const RAL_CLASSIC: RalColor[] = DATA.map(([code, name, hex]) => ({ code, name, hex }));

const byCode = new Map(RAL_CLASSIC.map((c) => [c.code, c]));

/** "6024", "RAL 6024", "R6024" → Eintrag */
export function findRal(input: string | null | undefined): RalColor | undefined {
	const m = /(\d{4})/.exec(input ?? '');
	return m ? byCode.get(m[1]) : undefined;
}

const fold = (s: string) => s.toLowerCase().replace(/ä/g, 'ae').replace(/ö/g, 'oe').replace(/ü/g, 'ue').replace(/ß/g, 'ss');

/** Suche nach Nummer ("60", "6024") oder Name ("verkehrsgr") */
export function searchRal(query: string, limit = 8): RalColor[] {
	const q = fold(query.trim().replace(/^ral\s*/i, ''));
	if (!q) return RAL_CLASSIC.filter((c) => /^(1023|3020|5017|6024|9016|9017|2009|7042)$/.test(c.code));
	const byNumber = /^\d+$/.test(q);
	return RAL_CLASSIC.filter((c) => (byNumber ? c.code.startsWith(q) : fold(c.name).includes(q))).slice(0, limit);
}
